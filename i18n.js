const supportedLanguages = ["zh", "en"];

function initialLanguage() {
  const explicit = new URL(location.href).searchParams.get("lang");
  if (supportedLanguages.includes(explicit)) return explicit;
  try {
    const saved = localStorage.getItem("skywalker-language");
    if (supportedLanguages.includes(saved)) return saved;
  } catch { /* Storage can be unavailable in private browsing. */ }
  return "en"; // Every new visitor starts in English; a chosen language is remembered.
}

let language = initialLanguage();
document.documentElement.lang = language === "zh" ? "zh-CN" : "en";

function t(key, values = {}) {
  const text = messages[language][key];
  if (typeof text !== "string") throw new Error(`Missing ${language} translation: ${key}`);
  return text.replace(/\{(\w+)\}/g, (match, name) => values[name] ?? match);
}

function otherLanguage(value = language) { return value === "zh" ? "en" : "zh"; }

/* Translate the page chrome (header, footer, skip link, meta). index.html calls this right after
   the header is parsed so the first paint is already in the visitor's language; app.js calls it
   on every change. Each label also records the other edition's text in data-alt, and the
   stylesheet reserves that width underneath the visible label, so switching language changes
   the words and moves nothing. */
function applyLanguageChrome() {
  document.documentElement.lang = language === "zh" ? "zh-CN" : "en";
  const other = messages[otherLanguage()];
  document.querySelectorAll("[data-i18n]").forEach(el => {
    el.textContent = t(el.dataset.i18n);
    el.dataset.alt = other[el.dataset.i18n];
  });
  document.querySelectorAll("nav[data-nav]").forEach(nav => nav.setAttribute("aria-label", t("navLabel")));
  const switcher = document.querySelector(".language-switch");
  if (switcher) {
    switcher.setAttribute("aria-label", t("languageLabel"));
    switcher.querySelectorAll("[data-language]").forEach(button => {
      button.setAttribute("aria-pressed", String(button.dataset.language === language));
      button.dataset.alt = button.textContent;
    });
  }
  const description = document.querySelector('meta[name="description"]');
  if (description) description.content = t("metaDescription");
}

function locale() { return language === "zh" ? "zh-CN" : "en-US"; }
function formatDate(value) {
  if (!value) return "";
  const date = new Date(value.length === 10 ? `${value}T12:00:00Z` : value.replace(" ", "T") + (/Z$|[+-]\d{2}:\d{2}$/.test(value) ? "" : "Z"));
  if (Number.isNaN(date.getTime())) return value;
  return new Intl.DateTimeFormat(locale(), { year: "numeric", month: "short", day: "numeric", timeZone: "UTC" }).format(date);
}
